def run_triangulation(pkl_file, config_file, calib_file, out_file, n_cams=8, use_gt=False):
    # Load 2D pose estimation results from the .pkl file
    with open(pkl_file, 'rb') as f:
        pose2d_results = pickle.load(f)

    print('Loaded {} samples from {}'.format(len(pose2d_results), pkl_file))
    config_dict = toml.load(config_file)
    
    # Extract camera names dynamically from prediction image paths
    detected_cams = set()
    for res in pose2d_results:
        path = res.get('img_path', '')
        dir_name = os.path.basename(os.path.dirname(path))
        if '-Camera' in dir_name:
            detected_cams.add(dir_name)
        else:
            filename = os.path.basename(path)
            if '-Camera' in filename:
                parts = filename.split('-frame_')[0]
                detected_cams.add(parts)

    if detected_cams:
        cameras = sorted(list(detected_cams))
    else:
        cameras = ['Camera1_M11139', 'Camera2_M11140', 'Camera3_M11141', 'Camera4_M11458', 'Camera5_M11459', 'Camera6_M11461', 'Camera7_M11462', 'Camera8_M11463']
        
    cams = cameras[:n_cams]
    out = extract_keypoints_from_preds(pose2d_results, cams=cams, use_gt=use_gt)

    for keypoints, frames, base_path, seq in out:
        print('Triangulating sequence:', seq)
        # Create destination directory if not exists
        os.makedirs(os.path.dirname(os.path.abspath(out_file)), exist_ok=True)
        triangulate_all(config_dict, calib_file, keypoints, n_cams=n_cams, cams=cams, trc_path=out_file)
        break


